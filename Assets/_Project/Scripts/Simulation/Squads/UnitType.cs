namespace Marchlands.Simulation.Squads
{
    /// <summary>Род войск отряда.</summary>
    public enum UnitType
    {
        /// <summary>Гренадёры: отборная пехота — крепче мораль, сильнее в штыковой; дороже и дольше в найме.</summary>
        Grenadiers,

        /// <summary>Фузилёры: основная линейная пехота, дешевле и быстрее в найме, чем гренадёры.</summary>
        Fusiliers,

        /// <summary>Конница: дорогая, быстрая, сильна в рукопашной, не стреляет. Нанимается в конюшне.</summary>
        Cavalry,

        /// <summary>Ждущие у казармы или конюшни люди: стоят толпой, стреляют вразнобой, отбиваются слабее. Не управляются.</summary>
        Recruits
    }
}
